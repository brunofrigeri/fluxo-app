// Turns the tokens into CSS. Output is committed as tokens.css and checked for drift by the tests.
import { dark, light, type Theme } from "./colors";
import { icons } from "./icons";
import { fontFamily, type, type TextStyle } from "./typography";

const kebab = (k: string) => k.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase();
/** 0.04 -> ".04", -0.02 -> "-.02" */
const num = (n: number) => String(n).replace(/^(-?)0\./, "$1.");

const vars = (t: Theme) =>
  Object.entries(t)
    .map(([k, v]) => `--${kebab(k)}:${v};`)
    .join("\n");

const svg = (i: { strokeWidth: number; paths: readonly string[] }) =>
  `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='${i.strokeWidth}' stroke-linecap='round' stroke-linejoin='round'>` +
  i.paths.map((d) => `<path d='${d}'/>`).join("") +
  `</svg>`;

const dataUri = (s: string) =>
  `url("data:image/svg+xml,${s.replace(/</g, "%3C").replace(/>/g, "%3E")}")`;

export function buildCss(): string {
  const iconEntries = Object.entries(icons);
  return [
    "/* GENERATED by packages/tokens (npm run generate -w @fluxo/tokens). Do not edit by hand. */",
    `.fx{\n--font-sans:${fontFamily.sansStack};\n${vars(light)}\n}`,
    `.fx[data-theme=dark]{\n${vars(dark)}\n}`,
    "/* type scale */",
    ...Object.entries(type).map(([name, t]) => {
      const s: TextStyle = t;
      return (
        `.t-${name}{font-size:${s.fontSize}px;line-height:${s.lineHeight}px` +
        (s.fontWeight !== undefined ? `;font-weight:${s.fontWeight}` : "") +
        (s.letterSpacing !== undefined ? `;letter-spacing:${num(s.letterSpacing)}em` : "") +
        (s.uppercase ? ";text-transform:uppercase" : "") +
        "}"
      );
    }),
    "/* icons (stroke masks) */",
    `.fx{\n${iconEntries.map(([n, i]) => `--i-${n}:${dataUri(svg(i))};`).join("\n")}\n}`,
    iconEntries.map(([n]) => `.i-${n}{--m:var(--i-${n})}`).join("\n"),
    "",
  ].join("\n");
}
